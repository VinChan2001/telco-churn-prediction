import pandas as pd
import streamlit as st


st.set_page_config(
    page_title="Telco Churn Prediction Dashboard",
    layout="wide"
)


@st.cache_data
def load_data():
    scored_customers = pd.read_csv("data/processed/scored_churn_customers.csv")
    risk_summary = pd.read_csv("data/processed/risk_segment_summary.csv")
    model_metrics = pd.read_csv("data/processed/model_metrics.csv")
    shap_importance = pd.read_csv("data/processed/shap_feature_importance.csv")

    return scored_customers, risk_summary, model_metrics, shap_importance


scored_customers, risk_summary, model_metrics, shap_importance = load_data()

st.title("Telco Customer Churn Prediction Dashboard")

st.markdown(
    """
    This dashboard summarizes churn risk predictions generated by the trained XGBoost churn model.
    The model scores customers, assigns risk segments, and estimates annual revenue at risk.
    """
)

st.header("Model Performance")

col1, col2, col3, col4 = st.columns(4)

col1.metric("ROC AUC", round(model_metrics.loc[0, "roc_auc"], 3))
col2.metric("Churn Recall", round(model_metrics.loc[0, "churn_recall"], 3))
col3.metric("Churn Precision", round(model_metrics.loc[0, "churn_precision"], 3))
col4.metric("Churn F1", round(model_metrics.loc[0, "churn_f1"], 3))

st.header("Risk Segment Summary")

st.dataframe(risk_summary, use_container_width=True)

st.subheader("Customer Count by Risk Segment")

risk_order = ["Low Risk", "Medium Risk", "High Risk"]

risk_count_chart = (
    risk_summary
    .set_index("risk_segment")
    .loc[risk_order, "customer_count"]
)

st.bar_chart(risk_count_chart)

st.header("Customer-Level Churn Scores")

selected_segment = st.selectbox(
    "Filter by risk segment",
    ["All"] + sorted(scored_customers["risk_segment"].dropna().unique().tolist())
)

if selected_segment != "All":
    filtered_customers = scored_customers[
        scored_customers["risk_segment"] == selected_segment
    ]
else:
    filtered_customers = scored_customers

st.dataframe(
    filtered_customers[
        [
            "churn_probability",
            "predicted_churn",
            "risk_segment",
            "Monthly Charges",
            "estimated_annual_revenue",
        ]
    ].sort_values("churn_probability", ascending=False),
    use_container_width=True
)

st.header("Business Impact Summary")

flagged_customers = scored_customers[scored_customers["predicted_churn"] == 1]

customers_flagged = len(flagged_customers)
annual_revenue_flagged = flagged_customers["estimated_annual_revenue"].sum()

assumption_col1, assumption_col2 = st.columns(2)

retention_offer_cost = assumption_col1.number_input(
    "Retention offer cost per flagged customer ($)",
    min_value=0,
    value=50,
    step=5
)

assumed_retention_success_rate = assumption_col2.slider(
    "Assumed retention success rate",
    min_value=0.0,
    max_value=1.0,
    value=0.25,
    step=0.05
)

estimated_campaign_cost = customers_flagged * retention_offer_cost
estimated_revenue_saved = annual_revenue_flagged * assumed_retention_success_rate
estimated_net_value = estimated_revenue_saved - estimated_campaign_cost

biz_col1, biz_col2, biz_col3, biz_col4 = st.columns(4)

biz_col1.metric("Customers Flagged", f"{customers_flagged:,}")
biz_col2.metric("Flagged Annual Revenue", f"${annual_revenue_flagged:,.0f}")
biz_col3.metric("Estimated Campaign Cost", f"${estimated_campaign_cost:,.0f}")
biz_col4.metric("Estimated Net Value", f"${estimated_net_value:,.0f}")

st.header("Top At-Risk Customers for Retention Outreach")

top_n = st.slider(
    "Number of customers to show",
    min_value=10,
    max_value=100,
    value=25,
    step=5
)

top_at_risk = scored_customers.sort_values(
    "churn_probability",
    ascending=False
).head(top_n)

st.dataframe(
    top_at_risk[
        [
            "churn_probability",
            "risk_segment",
            "Monthly Charges",
            "estimated_annual_revenue",
            "predicted_churn",
        ]
    ],
    use_container_width=True
)

st.header("Top 20% High-Risk Targeting Scenario")

top_20_cutoff = scored_customers["churn_probability"].quantile(0.80)

top_20_customers = scored_customers[
    scored_customers["churn_probability"] >= top_20_cutoff
]

top_20_customer_count = len(top_20_customers)
top_20_annual_revenue = top_20_customers["estimated_annual_revenue"].sum()

top_20_campaign_cost = top_20_customer_count * retention_offer_cost
top_20_estimated_revenue_saved = top_20_annual_revenue * assumed_retention_success_rate
top_20_estimated_net_value = top_20_estimated_revenue_saved - top_20_campaign_cost

top20_col1, top20_col2, top20_col3, top20_col4 = st.columns(4)

top20_col1.metric("Top 20% Customers", f"{top_20_customer_count:,}")
top20_col2.metric("Top 20% Annual Revenue", f"${top_20_annual_revenue:,.0f}")
top20_col3.metric("Top 20% Campaign Cost", f"${top_20_campaign_cost:,.0f}")
top20_col4.metric("Top 20% Net Value", f"${top_20_estimated_net_value:,.0f}")

st.caption(
    "This scenario targets only the highest-risk 20% of customers by predicted churn probability."
)

st.markdown(
    """
    The top-20% targeting scenario is useful because retention teams often have limited campaign budgets.
    Instead of contacting every customer above a fixed churn threshold, the business can prioritize the
    highest-risk customers first.

    This allows the company to compare two strategies:

    - Threshold-based targeting: contact every customer with churn probability above the selected cutoff.
    - Top-percentile targeting: contact only the highest-risk customers, such as the top 20%.

    A focused top-risk strategy may reduce campaign cost while still protecting a large share of at-risk revenue.
    """
)

st.header("Global Model Explanation")

st.markdown(
    """
    SHAP values estimate how much each feature contributes to the model's churn predictions.
    Larger mean absolute SHAP values indicate features with stronger overall impact.
    """
)

top_shap_features = shap_importance.head(15).copy()

st.dataframe(
    top_shap_features,
    use_container_width=True
)

top_shap_chart = (
    top_shap_features
    .sort_values("mean_abs_shap_value", ascending=True)
    .set_index("feature")["mean_abs_shap_value"]
)

st.bar_chart(top_shap_chart)
